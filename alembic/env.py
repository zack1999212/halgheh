"""Alembic migration environment.

This environment is independent of FastAPI application startup: it reuses the
application's synchronous SQLAlchemy engine and ``DATABASE_URL`` from
``service.core.database`` and imports the SQLAlchemy ``Base`` metadata.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context

from service.core.database import DATABASE_URL, Base, engine

# Import every model module so its tables are registered on Base.metadata.
# New backend modules with models must be added here (or imported from a
# shared models package) so autogeneration can see them.
import service.auth.models  # noqa: F401,E402
import service.calendar.models  # noqa: F401,E402
import service.docs.models  # noqa: F401,E402
import service.notifications.models  # noqa: F401,E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

# Tables that must never appear in autogenerated diffs:
# * alembic_version is owned by Alembic.
# * schema_migrations is the tracking table left behind by the previous
#   custom migration runner.
EXCLUDED_TABLES = frozenset({"alembic_version", "schema_migrations"})


def include_object(object, name, type_, reflected, compare_to):
    """Exclude Alembic-internal and legacy tracking tables from autogeneration."""
    if type_ == "table" and name in EXCLUDED_TABLES:
        return False
    return True


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode (emit SQL without a live connection)."""
    context.configure(
        url=DATABASE_URL,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations against the application's synchronous engine."""
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            compare_server_default=True,
            include_object=include_object,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
